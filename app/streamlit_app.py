"""TraceGuard UI. Run: streamlit run app/streamlit_app.py

By default it reads demo/memos.json directly (no data, no key, no model needed). If the API_URL environment variable is set,
it calls the Phase 6a API instead (live mode when that server runs live). All render logic lives in src/ui/render.py.
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import streamlit as st  # noqa: E402

from src.ui import render  # noqa: E402
from src.ui.data import BundleSource, make_source  # noqa: E402

PAGES = ["Examples", "Memo view", "How it was evaluated", "Known limits"]
REPO_URL = os.environ.get("REPO_URL", "").rstrip("/")


@st.cache_resource
def source():
    return make_source() if os.environ.get("API_URL") else BundleSource(ROOT / "demo" / "memos.json")


def open_memo(tx_id):
    st.session_state["tx"] = int(tx_id)
    st.session_state["page"] = "Memo view"


def file_link(path):
    return f"[`{path}`]({REPO_URL}/blob/main/{path})" if REPO_URL else f"`{path}`"


def page_examples(src):
    st.header("Examples")
    st.write("Five nodes picked by the type of case, from the evaluation runs. Pick one to read its investigation memo.")
    for card in render.example_cards(src.examples()):
        with st.container(border=True):
            st.markdown(f"**Transaction {card['tx_id']}** · time step {card['time_step']} · {card['status']}")
            st.write(card["description"])
            st.button("Open memo", key=f"open{card['tx_id']}", on_click=open_memo, args=(card["tx_id"],))
    st.subheader("Other bundled memos")
    others = src.memos()
    choice = st.selectbox("Choose a memo", others, format_func=render.memo_option_label, index=None, placeholder="Select a transaction")
    if choice:
        st.button("Open selected memo", on_click=open_memo, args=(choice["tx_id"],))
    st.caption("Memos are generated by the agent; no ground-truth labels are shown anywhere in this app.")


def draw_claims(title, claims, note):
    st.markdown(f"#### {title}")
    st.caption(note)
    if not claims:
        st.write("(none)")
    for i, c in enumerate(claims, 1):
        st.markdown(f"{i}. {c.text}")
        for chip in c.chips:
            with st.expander(f"evidence · {chip.name}" + (f" ({chip.tool})" if chip.tool else "")):
                st.code(chip.text, language=None)


def page_memo(src):
    st.header("Memo view")
    memos = src.memos()
    options = [m["tx_id"] for m in memos]
    tx = st.session_state.get("tx")
    if getattr(src, "live", False):
        typed = st.number_input("Transaction id (live mode runs the agent; it can take a minute)", min_value=0, value=int(tx or 0), step=1)
        if st.button("Investigate") and typed:
            tx = st.session_state["tx"] = int(typed)
    else:
        idx = options.index(tx) if tx in options else None
        picked = st.selectbox("Transaction", options, index=idx, placeholder="Select a transaction",
                              format_func=lambda t: render.memo_option_label(next(m for m in memos if m["tx_id"] == t)))
        tx = st.session_state["tx"] = picked
    if not tx:
        st.info("Choose a transaction here, or open one from the Examples page.")
        return
    try:
        with st.spinner("Reading the memo..."):
            entry = src.get(tx)
    except LookupError as e:
        st.error(str(e))
        return
    if entry is None:
        st.error(f"No memo for transaction {tx}.")
        return
    v = render.memo_view(entry)
    st.subheader(f"Transaction {v.tx_id} · time step {v.time_step}")
    getattr(st, v.banner.level)(f"**{v.banner.title}.** {v.banner.text}")
    for line in v.risk:
        st.markdown(f"- {line}")
    if v.conflict:
        st.warning(f"**Signal conflict.** {v.conflict}")
    if v.summary:
        draw_claims("Executive summary", v.summary, "Written by the language model; each sentence is checked by the critic.")
    draw_claims("Activity description", v.claims,
                "Rendered by code from the tool outputs; open the evidence chips to see the cited tool output." if v.claims else "")
    st.markdown("#### Regulatory background")
    for b in v.background:
        with st.container(border=True):
            st.caption(f"{b['heading']} · {b['source_doc']}")
            st.write(b["text"])
            if b["quote"]:
                st.markdown(f"> {b['quote']}")
            st.caption(f"`{b['evidence_id']}`" + ("" if b["quotable"] else " · OCR text, not quoted"))
    if not v.background:
        st.write("(none: no risk-raising pattern matched, or none retrieved)")
    if v.next_checks:
        st.markdown("#### What a human analyst could check next")
        for c in v.next_checks:
            st.markdown(f"- {c}")
    st.markdown("#### Subject fields")
    for k, val in v.subject.items():
        st.markdown(f"- {k}: {val}")
    if v.removed or v.notes:
        st.markdown("#### Notes")
        for x in v.notes + v.removed:
            st.markdown(f"- {x}")
    with st.expander("Limitations of this memo"):
        for x in v.limitations:
            st.markdown(f"- {x}")
    st.markdown(f"**Recommendation:** {v.recommendation}")
    if v.trace:
        st.caption(f"Run: {v.trace.get('tool_calls')} tool calls, {v.trace.get('llm_calls')} LLM calls, "
                   f"{v.trace.get('critic_rounds')} critic rounds, {v.trace.get('latency_s')} s.")


def page_eval():
    st.header("How it was evaluated")
    st.write("Every experiment was pre-registered (spec committed before the runs) and the results are reported as they came out, "
             "including the ones that went against the design.")
    for item in render.EVAL_ITEMS:
        with st.container(border=True):
            st.subheader(item["title"])
            st.write(item["text"])
            fig = ROOT / item["figure"] if item.get("figure") else None
            if fig and fig.exists():
                st.image(str(fig), caption=item["caption"])
            st.markdown("Report: " + file_link(item["report"]))


def page_limits():
    st.header("Known limits")
    for x in render.LIMITS:
        st.markdown(f"- {x}")


def main():
    st.set_page_config(page_title="TraceGuard", layout="wide")
    st.sidebar.title("TraceGuard")
    st.sidebar.caption("Flags suspicious Bitcoin transactions (Elliptic dataset) and drafts grounded memos for a human analyst.")
    page = st.sidebar.radio("Page", PAGES, key="page")
    src = source()
    st.sidebar.caption("Mode: " + ("API, live" if getattr(src, "live", False) else "API, demo" if os.environ.get("API_URL") else "bundled demo memos"))
    {"Examples": lambda: page_examples(src), "Memo view": lambda: page_memo(src), "How it was evaluated": page_eval,
     "Known limits": page_limits}[page]()


main()
